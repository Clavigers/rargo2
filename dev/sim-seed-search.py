#!/usr/bin/env python3
"""Search fresh simulator seeds and report each failure shape once."""

import argparse
import fcntl
import hashlib
import re
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

# rargo-sim --seeds A..B prints each Failure followed by its replay command.
FAILURE = re.compile(
    r"^seed (\d+): ([^\n]+?) broken at \d+ ms: (.*?)\nreplay: rargo-sim --seed \1$",
    re.MULTILINE | re.DOTALL,
)
SUMMARY = re.compile(r"^(\d+) of (\d+) seeds failed$", re.MULTILINE)
MARKER = re.compile(r"^<!-- rargo-sim-signature: ([0-9a-f]{64}) -->$", re.MULTILINE)
VALUES = re.compile(
    r'"(?:[^"\\]|\\.)*"'
    r"|\b(?:0x[0-9a-fA-F]+|[0-9a-fA-F]{32,}|\d+)\b"
)


def message_shape(detail):
    # Simulator diagnostics include IDs, times, hashes, generated bytes and
    # lists of clients and actions still waiting. Preserve the surrounding text.
    shape = VALUES.sub("?", detail)
    shape = re.sub(r"\[(?:\?(?:, \?)*)?\]", "[…]", shape)
    shape = re.sub(r"(client \? round \? waits on \[…\])(?:; \1)+", r"\1", shape)
    return " ".join(shape.split())


@dataclass(frozen=True)
class Failure:
    seed: int
    invariant: str
    detail: str

    @property
    def signature(self):
        key = f"{self.invariant}\n{message_shape(self.detail)}"
        return hashlib.sha256(key.encode()).hexdigest()


def run_batch(sim, start, end):
    result = subprocess.run(
        [sim, "--seeds", f"{start}..{end}"],
        stdout=subprocess.PIPE,
        text=True,
        encoding="utf-8",
    )
    failures = [
        Failure(int(seed), invariant, detail)
        for seed, invariant, detail in FAILURE.findall(result.stdout)
    ]
    summary = SUMMARY.findall(result.stdout)
    seeds = [failure.seed for failure in failures]
    if (
        summary != [(str(len(failures)), str(end - start))]
        or result.returncode != int(bool(failures))
        or seeds != sorted(set(seeds))
        or any(not start <= seed < end for seed in seeds)
    ):
        raise RuntimeError(
            f"unexpected simulator result for {start}..{end} "
            f"(exit {result.returncode})\n{result.stdout}"
        )
    return failures


def known_signatures(repo):
    # Include closed reports and exhaust pagination so a restart after issue
    # creation can recover even if the local seed cursor was never updated.
    bodies = subprocess.check_output(
        [
            "gh", "api", "--paginate",
            f"repos/{repo}/issues?state=all&per_page=100",
            "--jq", '.[] | select(has("pull_request") | not) | (.body // "")',
        ],
        text=True,
        encoding="utf-8",
    )
    return set(MARKER.findall(bodies))


def report_failures(repo, failures):
    if not failures:
        return
    known = known_signatures(repo)
    for failure in failures:
        signature = failure.signature
        if signature in known:
            continue
        detail = "\n".join(f"    {line}" for line in failure.detail.splitlines())
        body = (
            f"Seed {failure.seed} broke the invariant **{failure.invariant}**.\n\n"
            f"{detail}\n\n"
            f"Replay with `rargo-sim --seed {failure.seed}`.\n\n"
            f"<!-- rargo-sim-signature: {signature} -->\n"
        )
        title = f"rargo-sim: {failure.invariant} failed (seed {failure.seed})"
        subprocess.run(
            ["gh", "issue", "create", "--repo", repo, "--label", "bug",
             "--title", title, "--body-file", "-"],
            input=body,
            text=True,
            encoding="utf-8",
            check=True,
        )
        known.add(signature)


def positive_int(value):
    number = int(value)
    if number < 1:
        raise argparse.ArgumentTypeError("expected a positive integer")
    return number


def main():
    parser = argparse.ArgumentParser(
        description=__doc__,
        epilog="Build the simulator with 'rargo build -p rargo-sim'. "
        "Use one persistent state directory and one runner per GitHub repository. "
        "The GitHub CLI must be authenticated with permission to file issues.",
    )
    parser.add_argument("--repo", required=True, metavar="OWNER/REPO",
                        help="GitHub repository to receive bug reports")
    parser.add_argument("--state-dir", required=True, type=Path,
                        help="persistent directory for the seed cursor and process lock")
    parser.add_argument("--sim", default="rargo-sim", help="path to the simulator binary")
    parser.add_argument("--batch-size", type=positive_int, default=1000,
                        help="seeds per range (default 1000)")
    parser.add_argument("--batches", type=positive_int,
                        help="stop after this many ranges (default runs continuously)")
    args = parser.parse_args()

    try:
        args.state_dir.mkdir(parents=True, exist_ok=True)
        cursor = args.state_dir / "next-seed"
        with (args.state_dir / "search.lock").open("a") as lock:
            try:
                fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
            except BlockingIOError as error:
                raise RuntimeError(f"seed search already running in {args.state_dir}") from error

            start = int(cursor.read_text()) if cursor.exists() else 600
            remaining = args.batches
            while remaining is None or remaining > 0:
                end = start + args.batch_size
                if not 600 <= start < end < 2**64:
                    raise RuntimeError(f"seed range outside 600..{2**64 - 1}: {start}..{end}")
                failures = run_batch(args.sim, start, end)
                report_failures(args.repo, failures)
                temporary = cursor.with_suffix(".tmp")
                temporary.write_text(f"{end}\n")
                temporary.replace(cursor)
                print(f"seeds {start}..{end}: {len(failures)} failed", flush=True)
                start = end
                if remaining is not None:
                    remaining -= 1
    except KeyboardInterrupt:
        return 130
    except (OSError, ValueError, RuntimeError, subprocess.CalledProcessError) as error:
        print(f"seed search: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
