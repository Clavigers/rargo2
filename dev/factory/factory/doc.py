"""The reference half of DATA-MODEL.md, generated from machines.py and
model.py so that it cannot drift from them."""
from __future__ import annotations

import inspect

from . import machines as M
from . import model as m

BEGIN = "<!-- generated by python -m factory doc; do not edit below -->"


def _type(s: dict, defs: dict) -> str:
    if "$ref" in s:
        return _type(defs[s["$ref"].split("/")[-1]], defs)
    if "anyOf" in s:
        return " or ".join(_type(x, defs) for x in s["anyOf"] if x.get("type") != "null")
    if "enum" in s:
        return " \\| ".join(f"`{v}`" for v in s["enum"])
    if "const" in s:
        return f"`{s['const']}`"
    if s.get("type") == "array":
        return f"set of {_type(s['items'], defs)}"
    if s.get("type") == "object":
        return s.get("title", "object")
    return {"integer": "int", "string": "text"}.get(s.get("type", ""), s.get("type", "?"))


def _fields(cls) -> str:
    js = cls.model_json_schema()
    defs, req = js.get("$defs", {}), set(js.get("required", []))
    out = []
    for name, s in js["properties"].items():
        if name == "event":
            continue
        opt = "" if name in req else "?"
        out.append(f"`{name}{opt}`: {_type(s, defs)}")
    return "<br>".join(out) or "—"


def render() -> str:
    o = [BEGIN, "", "## Machines", ""]
    for mc in M.MACHINES:
        o.append(f"### {mc.name} " + (f"(one per {mc.key})" if mc.key else "(one)"))
        o.append("")
        o.append(mc.meaning)
        o.append("")
        o.append("Starts in " + ", ".join(f"`{s}`" for s in sorted(mc.initial)) + ".")
        o.append("")
        for a in mc.states:
            outs = sorted(b for (x, b) in mc.edges if x is a)
            o.append(f"- `{a}` → " + (", ".join(f"`{b}`" for b in outs) if outs else "(final)"))
        o.append("")
    o += ["## Events", "",
          "| Event | Nature | Written by | Fields | Must be true |",
          "|---|---|---|---|---|"]
    for cls in m.EVENTS:
        name = cls.model_fields["event"].annotation.__args__[0]
        actors = ", ".join(sorted(cls.actors))
        rule = " ".join(inspect.getdoc(cls).split()) if cls.__doc__ else ""
        o.append(f"| `{name}` | {cls.nature} | {actors} | {_fields(cls)} | {rule} |")
    return "\n".join(o) + "\n"


def splice(text: str) -> str:
    head = text.split(BEGIN)[0].rstrip()
    return head + "\n\n" + render()
